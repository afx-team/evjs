/**
 * Replace the framework-owned `.ev` tree with one validated IR snapshot. The
 * complete BuildPlan has its own framework snapshot, while the compact manifest
 * links graph, generated artifacts, and final entry projections for inspection.
 */
async function writeGeneratedIR(
  cwd: string,
  graph: CoreGraph,
  plan: BuildPlan,
  modules: InternalGeneratedModule[],
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  const rootDir = path.resolve(cwd, GENERATED_IR_DIR);
  const queueKey = path.join(
    await fs.realpath(path.dirname(rootDir)),
    path.basename(rootDir),
  );
  const previousWrite =
    generatedIRWriteQueues.get(queueKey) ?? Promise.resolve();
  const currentWrite = previousWrite
    .catch(() => undefined)
    .then(() =>
      writeGeneratedIRUnlocked(cwd, rootDir, graph, plan, modules, generated),
    );
  generatedIRWriteQueues.set(queueKey, currentWrite);

  try {
    await currentWrite;
  } finally {
    if (generatedIRWriteQueues.get(queueKey) === currentWrite) {
      generatedIRWriteQueues.delete(queueKey);
    }
  }
}

async function writeGeneratedIRUnlocked(
  cwd: string,
  rootDir: string,
  graph: CoreGraph,
  plan: BuildPlan,
  modules: InternalGeneratedModule[],
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  await ensureSafeGeneratedRoot(rootDir);

  const modulesByKey = new Map(modules.map((module) => [module.key, module]));
  const declarationModules = modules.filter(
    (
      module,
    ): module is InternalGeneratedModule & {
      resolvedDeclarationSource: string;
      declarationFile: string;
      absoluteDeclarationFile: string;
    } =>
      module.resolvedDeclarationSource !== undefined &&
      module.declarationFile !== undefined &&
      module.absoluteDeclarationFile !== undefined,
  );
  await assertGeneratedTypesDiscoveryCanSync(cwd, generated);
  if (declarationModules.length > 0) {
    await ensureSafeGeneratedTypesCompanionRoot(cwd);
  }

  const expectedFiles = new Set([
    path.join(rootDir, GENERATED_IR_TYPES),
    path.join(rootDir, GENERATED_IR_MANIFEST),
    path.join(rootDir, "framework/core-graph.json"),
    path.join(rootDir, "framework/build-plan.json"),
    ...modules.map((module) => module.absoluteFile),
    ...generated.entries.map((entry) => path.resolve(cwd, entry.file)),
  ]);
  const writes = await Promise.allSettled([
    writeGeneratedTypes(cwd, rootDir, generated),
    ...writeGeneratedFrameworkFiles(cwd, rootDir, graph, plan),
    ...modules.map((module) =>
      writeGeneratedModule(cwd, rootDir, module, modulesByKey),
    ),
    ...declarationModules.map((module) =>
      writeGeneratedDeclarationCompanion(cwd, module),
    ),
    ...generated.entries.map((entry) =>
      writeGeneratedEntry(cwd, rootDir, plan, entry),
    ),
  ]);
  const failedWrite = writes.find(
    (result): result is PromiseRejectedResult => result.status === "rejected",
  );
  if (failedWrite) throw failedWrite.reason;

  await removeStaleGeneratedFiles(rootDir, rootDir, expectedFiles);
  await syncGeneratedTypesCompanionRoot(cwd, declarationModules);
  await syncGeneratedTypesDiscoveryFile(cwd, rootDir, generated);

  await writeOwnedOutputFileIfChanged(
    rootDir,
    path.join(rootDir, GENERATED_IR_MANIFEST),
    `${JSON.stringify(createManifestView(plan, graph), null, 2)}\n`,
    "generated IR manifest",
  );
}

async function preflightGeneratedIRWrite(
  cwd: string,
  modules: readonly InternalGeneratedModule[],
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  await assertSafeGeneratedRootCanMaterialize(
    path.resolve(cwd, GENERATED_IR_DIR),
  );
  await assertGeneratedTypesDiscoveryCanSync(cwd, generated);
  if (
    modules.some(
      (module) =>
        module.resolvedDeclarationSource !== undefined &&
        module.declarationFile !== undefined &&
        module.absoluteDeclarationFile !== undefined,
    )
  ) {
    await assertGeneratedTypesCompanionRootCanMaterialize(cwd);
  }
}

async function assertGeneratedTypesCompanionRootCanMaterialize(
  cwd: string,
): Promise<void> {
  const sourceRoot = path.resolve(cwd, "src");
  const sourceRootStats = await fs.lstat(sourceRoot);
  if (!sourceRootStats.isDirectory() || sourceRootStats.isSymbolicLink()) {
    throw new Error(
      `[evjs] Refusing to materialize declaration-only companions through non-directory source root "${sourceRoot}".`,
    );
  }

  const generatedParent = path.join(sourceRoot, ".ev");
  let generatedParentStats: Awaited<ReturnType<typeof fs.lstat>>;
  try {
    generatedParentStats = await fs.lstat(generatedParent);
  } catch (error) {
    if (isMissingPathError(error)) return;
    throw error;
  }
  if (
    !generatedParentStats.isDirectory() ||
    generatedParentStats.isSymbolicLink()
  ) {
    throw new Error(
      `[evjs] Refusing to materialize declaration-only companions through non-directory path "${generatedParent}".`,
    );
  }

  const companionRoot = path.join(generatedParent, "types");
  let companionRootStats: Awaited<ReturnType<typeof fs.lstat>>;
  try {
    companionRootStats = await fs.lstat(companionRoot);
  } catch (error) {
    if (isMissingPathError(error)) return;
    throw error;
  }
  if (
    !companionRootStats.isDirectory() ||
    companionRootStats.isSymbolicLink()
  ) {
    throw new Error(
      `[evjs] Refusing to materialize declaration-only companions through non-directory path "${companionRoot}".`,
    );
  }
  await assertGeneratedTreeHasNoSymlinks(companionRoot);

  const marker = await readGeneratedTypesCompanionMarker(
    path.join(companionRoot, GENERATED_TYPES_COMPANION_MARKER_FILE),
  );
  if (marker === "owned") return;
  if (marker === "absent" && (await fs.readdir(companionRoot)).length === 0) {
    return;
  }
  throw new Error(
    `[evjs] Refusing to overwrite user-authored declaration companion directory "${companionRoot}". Remove or rename it before using generated alias declarations.`,
  );
}

async function ensureSafeGeneratedTypesCompanionRoot(
  cwd: string,
): Promise<void> {
  const sourceRoot = path.resolve(cwd, "src");
  const sourceRootStats = await fs.lstat(sourceRoot);
  if (!sourceRootStats.isDirectory() || sourceRootStats.isSymbolicLink()) {
    throw new Error(
      `[evjs] Refusing to materialize declaration-only companions through non-directory source root "${sourceRoot}".`,
    );
  }

  const generatedParent = path.join(sourceRoot, ".ev");
  await ensurePlainDirectory(
    generatedParent,
    `[evjs] Refusing to materialize declaration-only companions through non-directory path "${generatedParent}".`,
  );

  const companionRoot = path.join(generatedParent, "types");
  let created = false;
  try {
    await fs.mkdir(companionRoot);
    created = true;
  } catch (error) {
    if (!isAlreadyExistsError(error)) throw error;
  }
  const companionRootStats = await fs.lstat(companionRoot);
  if (
    !companionRootStats.isDirectory() ||
    companionRootStats.isSymbolicLink()
  ) {
    throw new Error(
      `[evjs] Refusing to materialize declaration-only companions through non-directory path "${companionRoot}".`,
    );
  }
  await assertGeneratedTreeHasNoSymlinks(companionRoot);

  const markerFile = path.join(
    companionRoot,
    GENERATED_TYPES_COMPANION_MARKER_FILE,
  );
  if (!created) {
    const marker = await readGeneratedTypesCompanionMarker(markerFile);
    if (marker === "owned") return;
    if (marker === "absent") {
      const entries = await fs.readdir(companionRoot);
      if (entries.length === 0) {
        await writeOwnedOutputFileIfChanged(
          companionRoot,
          markerFile,
          GENERATED_TYPES_COMPANION_MARKER,
          "generated declaration companion marker",
        );
        return;
      }
    }
    throw new Error(
      `[evjs] Refusing to overwrite user-authored declaration companion directory "${companionRoot}". Remove or rename it before using generated alias declarations.`,
    );
  }

  await writeOwnedOutputFileIfChanged(
    companionRoot,
    markerFile,
    GENERATED_TYPES_COMPANION_MARKER,
    "generated declaration companion marker",
  );
}

async function syncGeneratedTypesCompanionRoot(
  cwd: string,
  modules: readonly (InternalGeneratedModule & {
    resolvedDeclarationSource: string;
    declarationFile: string;
    absoluteDeclarationFile: string;
  })[],
): Promise<void> {
  const companionRoot = path.resolve(cwd, GENERATED_TYPES_COMPANION_DIR);
  const markerFile = path.join(
    companionRoot,
    GENERATED_TYPES_COMPANION_MARKER_FILE,
  );
  const ownership =
    await readGeneratedTypesCompanionRootOwnership(companionRoot);

  if (modules.length === 0) {
    if (ownership !== "owned") return;
    await assertGeneratedTreeHasNoSymlinks(companionRoot);
    await removeStaleGeneratedFiles(companionRoot, companionRoot, new Set());
    await fs.rmdir(companionRoot);
    return;
  }

  if (ownership !== "owned") {
    throw new Error(
      `[evjs] Declaration companion ownership marker changed while materializing "${companionRoot}".`,
    );
  }
  const expectedFiles = new Set([
    markerFile,
    ...modules.map((module) => module.absoluteDeclarationFile),
  ]);
  await removeStaleGeneratedFiles(companionRoot, companionRoot, expectedFiles);
}

async function readGeneratedTypesCompanionRootOwnership(
  companionRoot: string,
): Promise<GeneratedOutputOwnership> {
  let stats: Awaited<ReturnType<typeof fs.lstat>>;
  try {
    stats = await fs.lstat(companionRoot);
  } catch (error) {
    if (isMissingPathError(error)) return "absent";
    throw error;
  }
  if (!stats.isDirectory() || stats.isSymbolicLink()) return "unowned";
  return readGeneratedTypesCompanionMarker(
    path.join(companionRoot, GENERATED_TYPES_COMPANION_MARKER_FILE),
  );
}

