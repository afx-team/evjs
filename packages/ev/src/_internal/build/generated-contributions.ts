async function readGeneratedTypesCompanionMarker(
  markerFile: string,
): Promise<"absent" | "owned" | "unowned"> {
  let stats: Awaited<ReturnType<typeof fs.lstat>>;
  try {
    stats = await fs.lstat(markerFile);
  } catch (error) {
    if (isMissingPathError(error)) return "absent";
    throw error;
  }
  if (!stats.isFile() || stats.isSymbolicLink()) return "unowned";
  return (await fs.readFile(markerFile, "utf-8")) ===
    GENERATED_TYPES_COMPANION_MARKER
    ? "owned"
    : "unowned";
}

