function validateEnum<T extends string>(
  value: unknown,
  allowed: readonly T[],
  label: string,
): T {
  if (typeof value === "string" && allowed.includes(value as T)) {
    return value as T;
  }
  throw new Error(
    `[evjs] ${label} must be one of: ${allowed.map((item) => `"${item}"`).join(", ")}.`,
  );
}

function validateRawString(value: unknown, label: string): string {
  if (typeof value !== "string") {
    throw new Error(`[evjs] ${label} must be a string.`);
  }
  return value;
}

function validateDeclarationSourceInput(
  value: unknown,
  label: string,
): GeneratedDeclarationSource {
  if (typeof value === "function") return value as GeneratedDeclarationSource;
  return validateDeclarationSourceText(value, label);
}

function validateDeclarationSourceText(value: unknown, label: string): string {
  if (
    typeof value !== "string" ||
    value.trim() === "" ||
    value.includes("\0") ||
    Buffer.byteLength(value, "utf-8") > MAX_DECLARATION_SOURCE_BYTES
  ) {
    throw new Error(
      `[evjs] ${label} must be non-empty declaration-module source without NUL bytes and at most ${MAX_DECLARATION_SOURCE_BYTES} UTF-8 bytes.`,
    );
  }
  return value;
}

function validateDeclarationSpecifier(value: string, label: string): void {
  if (
    value.length > MAX_DECLARATION_SPECIFIER_LENGTH ||
    value.startsWith(".") ||
    path.isAbsolute(value) ||
    value.includes("\\") ||
    value.includes("*") ||
    /\s/u.test(value) ||
    Array.from(value).some((character) => {
      const code = character.charCodeAt(0);
      return code <= 0x1f || code === 0x7f;
    })
  ) {
    throw new Error(
      `[evjs] ${label} must be an exact non-relative module specifier of at most ${MAX_DECLARATION_SPECIFIER_LENGTH} characters without wildcards, whitespace, or control characters.`,
    );
  }
}

function validateGeneratedModuleDeclaration(
  value: unknown,
  label: string,
): GeneratedModuleDeclaration {
  const declaration = readExactDataRecord(value, label, ["exports"]);
  const exportsValue = readBoundedDataArray(
    declaration.exports,
    `${label}.exports`,
    MAX_DECLARATION_EXPORTS,
  );

  const exposedNames = new Set<string>();
  const exports = exportsValue.map((entry, index) => {
    const entryLabel = `${label}.exports[${index}]`;
    const exportEntry = readExactDataRecord(entry, entryLabel, [
      "kind",
      "name",
      "typeParameters",
    ]);
    const kind = validateEnum(
      exportEntry.kind,
      ["value", "type"] as const,
      `${entryLabel}.kind`,
    );
    const hasTypeParameters = Object.hasOwn(exportEntry, "typeParameters");
    if (kind === "value" && hasTypeParameters) {
      throw new Error(
        `[evjs] ${entryLabel}.typeParameters is only allowed for type exports.`,
      );
    }
    if (kind === "type" && exportEntry.typeParameters !== "none") {
      throw new Error(
        `[evjs] ${entryLabel}.typeParameters must be exactly "none" to declare an audited non-generic named type export. Generic type exports are not supported.`,
      );
    }
    const name = validateDeclarationIdentifier(
      exportEntry.name,
      `${entryLabel}.name`,
      kind,
    );
    if (exposedNames.has(name)) {
      throw new Error(
        `[evjs] ${label}.exports exposes duplicate name "${name}".`,
      );
    }
    exposedNames.add(name);
    if (kind === "value") return Object.freeze({ kind, name });
    return Object.freeze({ kind, name, typeParameters: "none" as const });
  });
  return Object.freeze({ exports: Object.freeze(exports) });
}

function readExactDataRecord(
  value: unknown,
  label: string,
  allowedKeys: readonly string[],
): Record<string, unknown> {
  assertRecord(value, label);
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) {
    throw new Error(`[evjs] ${label} must be a plain data object.`);
  }
  const allowed = new Set(allowedKeys);
  const descriptors = Object.getOwnPropertyDescriptors(value);
  const result: Record<string, unknown> = {};
  for (const key of Reflect.ownKeys(descriptors)) {
    if (typeof key !== "string") {
      throw new Error(`[evjs] ${label} must not contain symbol fields.`);
    }
    if (!allowed.has(key)) {
      throw new Error(`[evjs] ${label} contains unexpected field "${key}".`);
    }
    const descriptor = descriptors[key];
    if (!descriptor || !("value" in descriptor) || !descriptor.enumerable) {
      throw new Error(
        `[evjs] ${label}.${key} must be an enumerable data property.`,
      );
    }
    result[key] = descriptor.value;
  }
  return result;
}

function readBoundedDataArray(
  value: unknown,
  label: string,
  maximumLength: number,
): unknown[] {
  if (
    !Array.isArray(value) ||
    Object.getPrototypeOf(value) !== Array.prototype
  ) {
    throw new Error(`[evjs] ${label} must be a plain array.`);
  }
  if (value.length === 0 || value.length > maximumLength) {
    throw new Error(
      `[evjs] ${label} must contain between 1 and ${maximumLength} entries.`,
    );
  }
  const descriptors = Object.getOwnPropertyDescriptors(value);
  for (const key of Reflect.ownKeys(descriptors)) {
    if (typeof key !== "string") {
      throw new Error(`[evjs] ${label} must not contain symbol fields.`);
    }
    if (key !== "length" && !/^(?:0|[1-9][0-9]*)$/u.test(key)) {
      throw new Error(`[evjs] ${label} contains unexpected field "${key}".`);
    }
  }

  return Array.from({ length: value.length }, (_, index) => {
    const descriptor = descriptors[String(index)];
    if (!descriptor || !("value" in descriptor) || !descriptor.enumerable) {
      throw new Error(
        `[evjs] ${label}[${index}] must be an enumerable data property.`,
      );
    }
    return descriptor.value;
  });
}

function validateDeclarationIdentifier(
  value: unknown,
  label: string,
  kind: "value" | "type",
): string {
  if (
    typeof value !== "string" ||
    value.length > MAX_DECLARATION_IDENTIFIER_LENGTH ||
    !DECLARATION_IDENTIFIER.test(value) ||
    DECLARATION_RESERVED_IDENTIFIERS.has(value) ||
    (kind === "type" && DECLARATION_TYPE_KEYWORDS.has(value))
  ) {
    throw new Error(
      `[evjs] ${label} must be a declaration-safe ${kind} identifier of at most ${MAX_DECLARATION_IDENTIFIER_LENGTH} characters.`,
    );
  }
  return value;
}

function validateHtmlAttrs(
  value: unknown,
  label: string,
): Record<string, string | boolean> {
  assertRecord(value, label);
  const attrs: Record<string, string | boolean> = {};
  for (const [name, attrValue] of Object.entries(value)) {
    assertTrimmedString(name, `${label} attribute name`);
    if (typeof attrValue !== "string" && typeof attrValue !== "boolean") {
      throw new Error(
        `[evjs] ${label}.${name} must be a string or boolean value.`,
      );
    }
    attrs[name] = attrValue;
  }
  return attrs;
}

function assertRecord(value: unknown, label: string): asserts value is object {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`[evjs] ${label} must be an object.`);
  }
}

function assertTrimmedString(value: unknown, label: string): void {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`[evjs] ${label} must be a non-empty string.`);
  }
  if (value !== value.trim()) {
    throw new Error(
      `[evjs] ${label} must not contain leading or trailing whitespace.`,
    );
  }
}

