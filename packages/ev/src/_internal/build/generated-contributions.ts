async function writeGeneratedTypes(
  cwd: string,
  rootDir: string,
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  const exactModuleDeclarations = generated.slots.flatMap((slot) =>
    slot.slot === "resolve.alias" && slot.declaration
      ? renderGeneratedModuleDeclaration(cwd, rootDir, generated, slot)
      : [],
  );
  await writeOwnedOutputFileIfChanged(
    rootDir,
    path.join(rootDir, GENERATED_IR_TYPES),
    [
      "/* This file is generated by evjs. Do not edit it directly. */",
      ...exactModuleDeclarations,
      'declare module "evjs:generated/*";',
      'declare module "*.css";',
      'declare module "*.less";',
      'declare module "*.scss";',
      'declare module "*.sass";',
      'declare module "*.json";',
      'declare module "*.svg";',
      'declare module "*.png";',
      'declare module "*.jpg";',
      'declare module "*.jpeg";',
      'declare module "*.gif";',
      'declare module "*.webp";',
      'declare module "*.avif";',
      "",
    ].join("\n"),
    "generated IR types",
  );
}

function renderGeneratedModuleDeclaration(
  cwd: string,
  rootDir: string,
  generated: GeneratedFrameworkPlan,
  slot: Extract<FrameworkSlotPlanItem, { slot: "resolve.alias" }>,
): string[] {
  if (!slot.declaration) return [];
  const generatedModule = generated.modules.find(
    (module) => module.file === slot.replacement,
  );
  if (!generatedModule?.declarationFile) {
    throw new Error(
      `[evjs] Exact generated declaration "${slot.specifier}" is missing its declaration-only companion.`,
    );
  }
  const importSpecifier = toDeclarationImportSpecifier(
    cwd,
    rootDir,
    generatedModule.declarationFile,
  );
  const declarations = slot.declaration.exports.map((item) => {
    if (item.kind === "value") {
      return `  export const ${item.name}: typeof import(${JSON.stringify(importSpecifier)}).${item.name};`;
    }
    return `  export type ${item.name} = import(${JSON.stringify(importSpecifier)}).${item.name};`;
  });
  return [
    `declare module ${JSON.stringify(slot.specifier)} {`,
    ...declarations,
    "}",
  ];
}

function toDeclarationImportSpecifier(
  cwd: string,
  rootDir: string,
  declarationFile: string,
): string {
  const companionRoot = path.resolve(cwd, GENERATED_TYPES_COMPANION_DIR);
  const absoluteFile = path.resolve(cwd, declarationFile);
  const relativeToCompanionRoot = path.relative(companionRoot, absoluteFile);
  if (
    relativeToCompanionRoot === ".." ||
    relativeToCompanionRoot.startsWith(`..${path.sep}`) ||
    path.isAbsolute(relativeToCompanionRoot) ||
    path.extname(absoluteFile) !== ".ts" ||
    !absoluteFile.endsWith(".d.ts")
  ) {
    throw new Error(
      `[evjs] Exact generated declaration companion must stay inside "${companionRoot}".`,
    );
  }
  const relativeFile = toPosixPath(path.relative(rootDir, absoluteFile));
  const scriptSpecifier = relativeFile.replace(/\.d\.ts$/u, ".js");
  return scriptSpecifier.startsWith(".")
    ? scriptSpecifier
    : `./${scriptSpecifier}`;
}

async function writeGeneratedDeclarationCompanion(
  cwd: string,
  module: InternalGeneratedModule & {
    resolvedDeclarationSource: string;
    absoluteDeclarationFile: string;
  },
): Promise<void> {
  const companionRoot = path.resolve(cwd, GENERATED_TYPES_COMPANION_DIR);
  await writeOwnedOutputFileIfChanged(
    companionRoot,
    module.absoluteDeclarationFile,
    [
      "/* eslint-disable */",
      "// This declaration-only companion is generated by evjs. Do not edit it directly.",
      module.resolvedDeclarationSource.trimEnd(),
      "",
    ].join("\n"),
    "generated declaration companion",
  );
}

async function writeGeneratedModule(
  cwd: string,
  rootDir: string,
  module: InternalGeneratedModule,
  modulesByKey: Map<string, InternalGeneratedModule>,
): Promise<void> {
  const resolvedSource =
    module.resolvedSource ??
    (typeof module.source === "function"
      ? module.source({
          importOf(ref) {
            const key = assertGeneratedModuleRef(ref).key;
            const referenced = modulesByKey.get(key);
            if (!referenced) {
              throw new Error(
                "[evjs] Generated module ref does not belong to this build.",
              );
            }
            return toGeneratedImportSpecifier(
              cwd,
              module.absoluteFile,
              referenced.file,
            );
          },
          importFile(file) {
            return toGeneratedImportSpecifier(cwd, module.absoluteFile, file);
          },
        })
      : module.source);
  await writeOwnedOutputFileIfChanged(
    rootDir,
    module.absoluteFile,
    withGeneratedHeader(resolvedSource, module.extension, {
      fromFile: module.absoluteFile,
      rootDir,
    }),
    "generated module",
  );
}

async function writeGeneratedEntry(
  cwd: string,
  rootDir: string,
  plan: BuildPlan,
  entry: GeneratedEntryPlan,
): Promise<void> {
  const buildEntry = plan.entries.find((item) => item.name === entry.name);
  if (!buildEntry) return;
  const absoluteFile = path.resolve(cwd, entry.file);
  await writeOwnedOutputFileIfChanged(
    rootDir,
    absoluteFile,
    withGeneratedHeader(
      createEntrySource(cwd, buildEntry, entry, plan),
      ".ts",
      {
        fromFile: absoluteFile,
        rootDir,
      },
    ),
    "generated entry",
  );
}

