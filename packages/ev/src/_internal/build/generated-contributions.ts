async function ensurePlainDirectory(
  directory: string,
  errorMessage: string,
): Promise<void> {
  try {
    await fs.mkdir(directory);
  } catch (error) {
    if (!isAlreadyExistsError(error)) throw error;
  }
  const stats = await fs.lstat(directory);
  if (!stats.isDirectory() || stats.isSymbolicLink()) {
    throw new Error(errorMessage);
  }
}

async function assertGeneratedTreeHasNoSymlinks(
  directory: string,
): Promise<void> {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const file = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(
        `[evjs] Refusing to materialize generated IR through symbolic link "${file}".`,
      );
    }
    if (entry.isDirectory()) {
      await assertGeneratedTreeHasNoSymlinks(file);
    }
  }
}

async function removeStaleGeneratedFiles(
  rootDir: string,
  directory: string,
  expectedFiles: ReadonlySet<string>,
): Promise<void> {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const file = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(
        `[evjs] Refusing to materialize generated IR through symbolic link "${file}".`,
      );
    }
    if (!entry.isDirectory()) {
      if (!expectedFiles.has(file)) {
        await removeOwnedOutputFile(rootDir, file, "stale generated output");
      }
      continue;
    }

    await removeStaleGeneratedFiles(rootDir, file, expectedFiles);
    try {
      await fs.rmdir(file);
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (code !== "ENOENT" && code !== "ENOTEMPTY") throw error;
    }
  }
}

async function assertGeneratedTypesDiscoveryCanSync(
  cwd: string,
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  if (!hasExactGeneratedDeclarations(generated)) return;
  const file = path.resolve(cwd, "src", GENERATED_TYPES_DISCOVERY_FILE);
  const existing = await readGeneratedTypesDiscoveryFile(file);
  if (existing && !existing.owned) {
    throw new Error(
      `[evjs] Refusing to overwrite user-authored TypeScript discovery file "${file}". Remove or rename it before using generated alias declarations.`,
    );
  }
}

async function syncGeneratedTypesDiscoveryFile(
  cwd: string,
  rootDir: string,
  generated: GeneratedFrameworkPlan,
): Promise<void> {
  const sourceRoot = path.resolve(cwd, "src");
  const file = path.join(sourceRoot, GENERATED_TYPES_DISCOVERY_FILE);
  const hasExactDeclarations = hasExactGeneratedDeclarations(generated);
  const existing = await readGeneratedTypesDiscoveryFile(file);

  if (!hasExactDeclarations) {
    if (existing?.owned) {
      await removeOwnedOutputFile(
        sourceRoot,
        file,
        "generated TypeScript discovery file",
      );
    }
    return;
  }

  if (existing && !existing.owned) {
    throw new Error(
      `[evjs] Refusing to overwrite user-authored TypeScript discovery file "${file}". Remove or rename it before using generated alias declarations.`,
    );
  }

  const reference = toPosixPath(
    path.relative(path.dirname(file), path.join(rootDir, GENERATED_IR_TYPES)),
  );
  const source = [
    GENERATED_TYPES_DISCOVERY_MARKER,
    "/* eslint-disable */",
    `/// <reference path=${JSON.stringify(
      reference.startsWith(".") ? reference : `./${reference}`,
    )} />`,
    "export {};",
    "",
  ].join("\n");
  await writeOwnedOutputFileIfChanged(
    sourceRoot,
    file,
    source,
    "generated TypeScript discovery file",
  );
}

function hasExactGeneratedDeclarations(
  generated: GeneratedFrameworkPlan,
): boolean {
  return generated.slots.some(
    (slot) => slot.slot === "resolve.alias" && slot.declaration !== undefined,
  );
}

async function readGeneratedTypesDiscoveryFile(
  file: string,
): Promise<{ owned: boolean } | undefined> {
  let stats: Awaited<ReturnType<typeof fs.lstat>>;
  try {
    stats = await fs.lstat(file);
  } catch (error) {
    if (isMissingPathError(error)) return undefined;
    throw error;
  }
  if (!stats.isFile() || stats.isSymbolicLink()) return { owned: false };

  const source = await fs.readFile(file, "utf-8");
  return {
    owned:
      source === GENERATED_TYPES_DISCOVERY_MARKER ||
      source.startsWith(`${GENERATED_TYPES_DISCOVERY_MARKER}\n`),
  };
}

export async function getGeneratedTypesDiscoveryOwnership(
  cwd: string,
): Promise<GeneratedOutputOwnership> {
  const existing = await readGeneratedTypesDiscoveryFile(
    path.resolve(cwd, "src", GENERATED_TYPES_DISCOVERY_FILE),
  );
  if (!existing) return "absent";
  return existing.owned ? "owned" : "unowned";
}

